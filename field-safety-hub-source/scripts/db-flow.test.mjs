import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";

test("Postgres RPCs enforce ownership, report validation and atomic action history", async () => {
  const db = new PGlite();
  const first = "10000000-0000-4000-8000-000000000001";
  const other = "20000000-0000-4000-8000-000000000002";
  let checks = 0;
  const eq = (a,b) => { assert.deepEqual(a,b); checks++; };
  async function rejects(fn, text) { await assert.rejects(fn, e => String(e.message).includes(text)); checks++; }
  const asUser = async id => {
    await db.exec("reset role; set role authenticated;");
    await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify(id ? {sub:id,email: id === first ? "first@example.test" : "other@example.test"} : {})]);
  };
  const mutate = async payload => (await db.query("select public.fsh_mutate($1::jsonb) as value",[JSON.stringify({siteId:"training",...payload})])).rows[0].value;
  const load = async (site="training") => (await db.query("select public.fsh_load($1) as value",[site])).rows[0].value;
  try {
    await db.exec(`
      create role anon; create role authenticated;
      create schema auth; create schema storage;
      create table auth.users(id uuid primary key,email text);
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      grant usage on schema auth,storage,public to anon,authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text,primary key(bucket_id,name));
      alter table storage.objects enable row level security;
      grant insert,select on storage.objects to authenticated;
      create function storage.foldername(name text) returns text[] language sql immutable as $$ select (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1] $$;
      insert into auth.users values ('${first}','first@example.test'),('${other}','other@example.test');
      insert into storage.objects(bucket_id,name) values ('field-safety-photos','${first}/photo.jpg'),('field-safety-photos','${other}/photo.jpg');
    `);
    await db.exec(readFileSync(new URL("../supabase/schema.sql",import.meta.url),"utf8"));
    await asUser(null);
    await rejects(() => load(),"로그인이 필요");
    await db.exec("reset role; set role anon;");
    await rejects(() => load(),"permission denied");
    await asUser(first);
    eq((await load()).reports.length,0);
    await mutate({action:"profile",name:"실습 작업자"});
    eq((await load()).profile,"실습 작업자");
    eq((await mutate({action:"seed"})).added,8);
    eq((await mutate({action:"seed"})).added,0);
    eq((await load()).reports.length,8);
    await rejects(() => mutate({action:"seed",siteId:"project"}),"실습 현장");
    await rejects(() => load("unknown"),"현장을 확인");
    const draft={action:"create",requestId:"30000000-0000-4000-8000-000000000003",floor:"6F",sector:"G-18",hazard:"정리불량",detail:"통로 주변에 폐자재가 쌓여 있습니다.",priority:"긴급",photos:[`${first}/photo.jpg`],ownerId:other};
    const created=await mutate(draft);
    eq((await mutate(draft)).id,created.id);
    await rejects(() => mutate({...draft,detail:"다른 내용으로 변경한 신고입니다."}),"요청 ID");
    let real=(await load()).reports.find(r=>r.id===created.id);
    eq(real.workerName,"실습 작업자");eq(real.history.length,1);eq(real.status,"접수");
    await rejects(() => mutate({...draft,requestId:"40000000-0000-4000-8000-000000000004",sector:"A-1"}),"check constraint");
    await rejects(() => mutate({...draft,requestId:"40000000-0000-4000-8000-000000000004",detail:"짧음"}),"check constraint");
    await rejects(() => mutate({...draft,requestId:"40000000-0000-4000-8000-000000000004",photos:[`${other}/photo.jpg`]}),"본인이 업로드");
    await rejects(() => mutate({...draft,requestId:"40000000-0000-4000-8000-000000000004",photos:Array(4).fill(`${first}/photo.jpg`)}),"최대 3장");
    const update=changes=>mutate({action:"update",id:real.id,updatedAt:real.updatedAt,status:real.status,assignee:"",note:"",resolutionPhotos:[],...changes});
    await rejects(() => update({status:"완료",assignee:"담당자",note:"정리정돈을 완료했습니다."}),"순서로 진행");
    await update({status:"확인",note:"현장 상태를 확인했습니다."});
    await rejects(() => update({status:"확인"}),"다른 화면");
    real=(await load()).reports.find(r=>r.id===created.id);
    eq(real.history.length,2);
    await rejects(() => update({status:"조치중"}),"담당자를 입력");
    await update({status:"조치중",assignee:"관리 담당자",note:"폐자재 정리 중입니다."});
    real=(await load()).reports.find(r=>r.id===created.id);
    await rejects(() => update({status:"완료",assignee:"관리 담당자",note:"완료"}),"5자 이상");
    await update({status:"완료",assignee:"관리 담당자",note:"폐자재 제거와 통로 확보를 완료했습니다.",resolutionPhotos:[`${first}/photo.jpg`]});
    real=(await load()).reports.find(r=>r.id===created.id);
    eq(real.history.map(h=>h.status),["접수","확인","조치중","완료"]);
    eq(real.resolutionPhotos,[`${first}/photo.jpg`]);
    assert.ok(real.resolvedAt);checks++;
    await rejects(() => update({status:"완료"}),"완료된 신고");
    await rejects(() => db.query("update public.fsh_reports set owner_id=$1 where id=$2",[other,real.id]),"permission denied");
    eq((await load("project")).reports.length,0);
    await asUser(other);
    eq((await load()).reports.length,0);
    eq((await db.query("select id from public.fsh_reports")).rows.length,0);
    eq((await db.query("select name from storage.objects")).rows.map(r=>r.name),[`${other}/photo.jpg`]);
    await rejects(() => update({status:"確認"}),"신고를 찾을 수");
    await rejects(() => db.query("insert into storage.objects(bucket_id,name) values('field-safety-photos',$1)",[`${first}/malicious.jpg`]),"row-level security");
    await asUser(first);
    eq((await mutate({action:"clearSamples"})).deleted,8);
    eq((await load()).reports.map(r=>r.id),[created.id]);
    eq((await load()).reports[0].history.length,4);
    await mutate({action:"demoLog",kind:"입장"});
    eq((await load()).logs[0].kind,"입장");
    eq((await load("project")).logs.length,0);
    const rls=(await db.query("select relname from pg_class where relnamespace='public'::regnamespace and relname like 'fsh_%' and relkind='r' and not relrowsecurity")).rows;
    eq(rls,[]);
    console.log(JSON.stringify({passed:true,checks,scope:"local Postgres-compatible engine; live Supabase connection not covered"}));
  } finally { await db.close(); }
});
